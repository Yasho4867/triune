@pytest.mark.tier2
def test_t2_f9_checksum_mismatch_detected_on_tampered_copy(
    e2e_repo_root: Path, tmp_path: Path
) -> None:
    """F9-T2-01: Tampering 1 byte of a copied dist artifact is detected by SHA-256 verification."""
    dist_dir = e2e_repo_root / "dist"
    sums_lines = (dist_dir / "SHA256SUMS.txt").read_text(encoding="utf-8").splitlines()
    first_digest, first_name = sums_lines[0].split()[0].upper(), sums_lines[0].split()[-1].lstrip("*")
    tampered = tmp_path / first_name
    shutil.copy2(dist_dir / first_name, tampered)
    raw = bytearray(tampered.read_bytes())
    raw[0] ^= 0xFF
    tampered.write_bytes(bytes(raw))
    assert sha256_file(tampered) != first_digest


