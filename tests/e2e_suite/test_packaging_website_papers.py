@pytest.mark.tier1
def test_t1_f9_dist_sha256sums_and_sidecars_match_artifacts(e2e_repo_root: Path) -> None:
    """F9-T1-01: dist/SHA256SUMS.txt and .sha256 sidecars match every listed artifact digest."""
    dist_dir = e2e_repo_root / "dist"
    sums_file = dist_dir / "SHA256SUMS.txt"
    assert sums_file.is_file(), f"Missing {sums_file}"

    entries: List[tuple[str, str]] = []
    for raw_line in sums_file.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line:
            continue
        parts = line.split()
        assert len(parts) >= 2, f"Malformed SHA256SUMS line: {raw_line!r}"
        digest = parts[0].strip().upper()
        rel_name = parts[-1].lstrip("*").strip()
        entries.append((digest, rel_name))

    assert len(entries) >= 3, f"Expected >=3 artifacts in SHA256SUMS.txt, got {entries}"
    for expected_hex, fname in entries:
        target = dist_dir / fname
        assert target.is_file(), f"Artifact listed in SHA256SUMS.txt missing: {target}"
        actual_hex = sha256_file(target)
        assert actual_hex == expected_hex, f"Digest mismatch for {fname}: {actual_hex} != {expected_hex}"

    # Verify sidecars for zip and any standalone EXEs generated by publish script
    for sidecar in dist_dir.glob("*.sha256"):
        txt = sidecar.read_text(encoding="utf-8").strip()
        expected_hex = txt.split()[0].upper()
        artifact = dist_dir / sidecar.name[: -len(".sha256")]
        assert artifact.is_file(), f"Sidecar {sidecar.name} missing target {artifact.name}"
        assert sha256_file(artifact) == expected_hex, f"Sidecar digest mismatch for {sidecar.name}"


